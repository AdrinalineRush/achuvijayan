"""Build responsive WebP copies without changing the original artwork.

Run from the project root with Python 3, ImageMagick and cwebp installed.
"""
import json
import hashlib
import re
from pathlib import Path
import subprocess
from concurrent.futures import ThreadPoolExecutor

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / 'assets/images/optimized'
OUTPUT.mkdir(parents=True, exist_ok=True)
# Only generate copies for source artwork referenced by the current page/data.
# Do not scan the manifest: that would retain retired variants forever.
content = '\n'.join((ROOT / name).read_text() for name in ('index.html', 'data.js'))
sources = sorted({ROOT / name for name in re.findall(
    r'''assets/(?:images|video)/[^\s<>"'?#]+\.(?:jpg|png)''', content)})


def convert(source):
    version = hashlib.sha256(source.read_bytes() + b'webp-q82-m6-v1').hexdigest()[:10]
    width, height = map(int, subprocess.check_output(
        ['magick', 'identify', '-format', '%w %h', str(source)], text=True).split())
    widths = sorted(set([min(width, 1280)] + [w for w in (320, 640, 960) if w < min(width, 1280)]))
    variants = []
    for target in widths:
        output = OUTPUT / f'{source.stem}-{version}-{target}.webp'
        if not output.exists() or not output.stat().st_size:
            subprocess.run(['cwebp', '-quiet', '-q', '82', '-m', '6', '-resize', str(target), '0',
                            str(source), '-o', str(output)], check=True)
        variants.append({'src': output.relative_to(ROOT).as_posix(), 'width': target})
    return source.relative_to(ROOT).as_posix(), {'width': width, 'height': height, 'variants': variants}


with ThreadPoolExecutor(max_workers=4) as pool:
    images = dict(pool.map(convert, sources))
manifest = '// Generated by scripts/optimize-images.py.\nconst RESPONSIVE_IMAGES = ' + json.dumps(images, separators=(',', ':')) + ';\n'
(ROOT / 'image-sources.js').write_text(manifest)
# This directory contains generated copies only. Drop superseded variants.
retained = {ROOT / v['src'] for image in images.values() for v in image['variants']}
for file in OUTPUT.glob('*.webp'):
    if file not in retained:
        file.unlink()
original = sum(source.stat().st_size for source in sources)
optimized = sum((ROOT / item['variants'][-1]['src']).stat().st_size for item in images.values())
print(f'{len(images)} images: original {original:,} bytes; largest WebP copies {optimized:,} bytes ({100*(1-optimized/original):.1f}% smaller).')
